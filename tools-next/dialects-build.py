"""Builds js/dialects-data.js and the dl.* keys of i18n/*.js from /tmp/dl (data.py + t_<lang>.py).
Run: python3 tools-next/dialects-build.py tools-next/dialects"""
import json, re, sys, runpy
src = sys.argv[1]
d = runpy.run_path(f'{src}/data.py')
js = ('// The SQL dialect table (#/dialects). Generated by tools-next/dialects-build.py — edit the source there.\n'
      '// cell: string = code | { c: code, w: word key (dl.w.*), v: "from version", x: 1 = not built in (c = a way around it) }\n'
      f"export const DL_DBS = {json.dumps(d['DBS'])};\n"
      f"export const DL_CATS = {json.dumps(d['CATS'])};\n"
      'export const DL_ITEMS = [\n' + ',\n'.join('  ' + json.dumps(i, ensure_ascii=False) for i in d['I']) + '\n];\n')
open('js/dialects-data.js', 'w').write(js)
for l in ['ja', 'easy', 'en', 'fr', 'id', 'vi', 'zh', 'ne', 'bn', 'si', 'my']:
    t = runpy.run_path(f'{src}/t_{l}.py')
    keys = dict(t['UI'])
    for k, (ti, no) in t['TN'].items():
        keys[f'dl.{k}.t'] = ti
        if no: keys[f'dl.{k}.n'] = no
    p = f'i18n/{l}.js'; s = open(p).read()
    s = re.sub(r'\n  "(?:dl\.[^"]+|nav\.dialects)": .*?(?=\n)', '', s)
    i = s.rstrip().rfind('};'); body = s[:i].rstrip()
    if not body.endswith(','): body += ','
    open(p, 'w').write(body + '\n' + ',\n'.join(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in keys.items()) + '\n};\n')
print('ok', len(d['I']))
